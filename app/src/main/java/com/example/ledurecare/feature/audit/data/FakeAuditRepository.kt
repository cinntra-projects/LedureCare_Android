import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject
import javax.inject.Singleton

/** Sample form options and a pretend submit that remembers what was sent. Nothing leaves the phone. */
@Singleton
class FakeAuditRepository @Inject constructor() : AuditRepository {

    private var lastDliNumber = 1064
    private val submitted = ConcurrentHashMap<String, SubmittedAudit>()

    override suspend fun getCatalog(): AppResult<AuditCatalog> {
        delay(300)
        return AppResult.Success(SampleCatalog)
    }

    override suspend fun submit(draft: AuditDraft): AppResult<SubmittedAudit> {
        delay(700)
        val dliNo = "DLI-${++lastDliNumber}"
        val record = SubmittedAudit(
            dliNo = dliNo,
            dealerName = draft.dealer?.name.orEmpty(),
            bpCode = draft.dealer?.bpCode.orEmpty(),
            address = draft.address,
            inspectionDate = draft.inspectionDate ?: LocalDate.now(),
            auditedBy = "Ravi Kumar",
            auditorRole = "Service Engineer",
            items = draft.items,
            notes = draft.notes,
            // The real file is generated by the backend; these are typical sample figures.
            form = GeneratedFile(name = "${dliNo}_Audit_Form.pdf", sizeBytes = 184_320, pages = 2),
            attachments = draft.files,
        )
        submitted[dliNo] = record
        return AppResult.Success(record)
    }

    override suspend fun getForEdit(returnId: Int): AppResult<AuditEdit> = AppResult.Failure(AppError.Http(404, "Not available in sample mode."))

    override suspend fun update(returnId: Int, draft: AuditDraft): AppResult<SubmittedAudit> = submit(draft)

    override suspend fun getSubmitted(dliNo: String): AppResult<SubmittedAudit> =
        submitted[dliNo]?.let { AppResult.Success(it) }
            ?: AppResult.Failure(AppError.Http(404, "Submitted DLI not found."))

    private companion object {
        val SampleCatalog = SampleAuditCatalog
    }
}

/** Sample products and conditions. The real form uses these too, until a products/conditions API is shared. */
internal val SampleAuditCatalog = AuditCatalog(
    products = listOf(
        Product("LD-2210", "Filter kit"),
        Product("LD-3105", "Control board"),
        Product("LD-4180", "Power adapter"),
        Product("LD-5020", "Sensor module"),
        Product("LD-6150", "Motor assembly"),
        Product("LD-7311", "Display panel"),
        Product("LD-8420", "Cable harness"),
        Product("LD-9005", "Relay switch"),
    ),
    conditions = listOf("Damaged", "Defective", "Expired", "Wrong supply"),
)
